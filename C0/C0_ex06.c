#include <unistd.h>

void ft_print_comb2(void)
{
	char v[5];
	int i;
	int j;

	i = 0;
	while (i <= 98)
	{
		j = i + 1;
		while (j <= 99)
		{
			v[0] = '0' + (i / 10);
			v[1] = '0' + (i % 10);
			v[2] = ' ';
			v[3] = '0' + (j / 10);
			v[4] = '0' + (j % 10);
			write(1, v, 5);
			if (i != 98 || j != 99)
				write(1, ",", 2);
			j++;
		}
		i++;
	}
}

int main(void)
{
	ft_print_comb2();
	return (0);
}
